// server/adminState.js
// Centralized server state for Administrator Dashboard & World Controller

import { personalities, AGENT_PERSONAS } from './ai/personalities.js';
import {db} from './db.js';

export const adminState = {
  // World parameters editable by Admin in real-time
  world: {
    fogDensity: 0.022,
    lightIntensity: 1.15,
    ambientColor: '#9180ab',
    gravity: 9.8,
    weather: 'clear', // 'clear' | 'spectral_fog' | 'halloween_eclipse' | 'neon_rain'
    timeOfDay: 'midnight'
  },

  // Live telemetry map: username -> { fps, ping, loadedChunks, memoryMB, drawCalls, x, y, z, ip, lastSeen }
  clientsTelemetry: new Map(),

  // Dynamic mutations log (objects generated by agents or admin)
  mutationsLog: [],

  // Update client telemetry from WebSocket message
  recordTelemetry(username, data, ip = '127.0.0.1') {
    const existing = this.clientsTelemetry.get(username) || {};
    this.clientsTelemetry.set(username, {
      ...existing,
      username,
      fps: typeof data.fps==='number'&&Number.isFinite(data.fps) ? Math.max(0,data.fps) : existing.fps ?? null,
      ping: typeof data.ping==='number'&&Number.isFinite(data.ping) ? Math.max(0,data.ping) : existing.ping ?? null,
      loadedChunks: Number.isFinite(Number(data.loadedChunks)) ? Number(data.loadedChunks) : existing.loadedChunks ?? 0,
      memoryMB: Number(data.memoryMB) || existing.memoryMB || 0,
      drawCalls: Number(data.drawCalls) || existing.drawCalls || 0,
      x: Number(data.x ?? existing.x ?? 0),
      y: Number(data.y ?? existing.y ?? 1.6),
      z: Number(data.z ?? existing.z ?? 10.5),
      ip: ip || existing.ip || '127.0.0.1',
      lastSeen: Date.now()
    });
  },

  removeClient(username) {
    this.clientsTelemetry.delete(username);
  },

  // Get aggregated metrics for dashboard
  getMetricsSnapshot(serverUptimeSeconds = 0) {
    const players = Array.from(this.clientsTelemetry.values()).map(p=>({...p,telemetryAgeMs:Date.now()-p.lastSeen,isStale:Date.now()-p.lastSeen>10000}));
    const count = players.length;

    let totalFps = 0;
    let totalPing = 0;
    for (const p of players) {
      totalFps += p.fps;
      totalPing += p.ping;
    }

    const fpsSamples=players.filter(p=>!p.isStale&&p.fps!==null),pingSamples=players.filter(p=>!p.isStale&&p.ping!==null);
    const avgFps = fpsSamples.length ? Number((fpsSamples.reduce((n,p)=>n+p.fps,0)/fpsSamples.length).toFixed(1)) : null;
    const avgPing = pingSamples.length ? Math.round(pingSamples.reduce((n,p)=>n+p.ping,0)/pingSamples.length) : null;

    return {
      server: {
        uptimeSeconds: Math.floor(serverUptimeSeconds),
        tickRateHz: 20,
        activePlayersCount: count,
        avgFps,
        avgPingMs: avgPing,
        totalWorldChunks: 100,
        cacheLimitPercent: 10
      },
      world: { ...this.world },
      players,
      agents: Object.values(personalities).filter(p=>['kanev','korshunov','maslennikov'].includes(p.id)).map(p => ({
        id: p.id,
        name: p.name,
        mood: p.mood || 'normal',
        systemPrompt: p.systemPrompt,
        factsCount: (p.facts || []).length,
        hasTask: !!p.task,
        codeDigit: p.codeDigit
      })),
      mutations: this.mutationsLog.slice(-15)
    };
  },

  // Update world settings
  updateWorldSettings(newSettings) {
    if (newSettings.fogDensity !== undefined) this.world.fogDensity = Number(newSettings.fogDensity);
    if (newSettings.lightIntensity !== undefined) this.world.lightIntensity = Number(newSettings.lightIntensity);
    if (newSettings.ambientColor !== undefined) this.world.ambientColor = String(newSettings.ambientColor);
    if (newSettings.gravity !== undefined) this.world.gravity = Number(newSettings.gravity);
    if (newSettings.weather !== undefined) this.world.weather = String(newSettings.weather);
    db.saveQuestProgress({extra:{settings:this.world}},'admin-world-settings');
    return { ...this.world };
  },

  // Update agent persona configuration
  updateAgentConfig(agentId, config) {
    const agent = personalities[agentId];
    if (!agent) return null;

    if (config.mood) agent.mood = config.mood;
    if (config.systemPrompt) agent.systemPrompt = config.systemPrompt;
    if (config.name) agent.name = config.name;

    if (AGENT_PERSONAS[agentId]) {
      AGENT_PERSONAS[agentId].mood = agent.mood;
      AGENT_PERSONAS[agentId].systemPrompt = agent.systemPrompt;
      if (config.name) AGENT_PERSONAS[agentId].name = config.name;
    }
    db.saveQuestProgress({extra:{config:{mood:agent.mood,systemPrompt:agent.systemPrompt,name:agent.name}}},'admin-agent:'+agentId);

    return agent;
  },

  // Record a world mutation event
  recordMutation(mutation) {
    const record = {
      id: `mut_${Date.now()}_${Math.random().toString(36).slice(2, 6)}`,
      timestamp: Date.now(),
      ...mutation
    };
    this.mutationsLog.push(record);
    if (this.mutationsLog.length > 50) this.mutationsLog.shift();
    return record;
  }
};
const storedWorld=db.getQuestProgress('admin-world-settings').settings;
if(storedWorld)Object.assign(adminState.world,storedWorld);
for(const id of ['kanev','korshunov','maslennikov']){
  const config=db.getQuestProgress('admin-agent:'+id).config;
  if(config){config.name=personalities[id].name;config.systemPrompt=config.systemPrompt?.replaceAll('Канев Константин Юрьевич','Канев Антон Игоревич').replaceAll('Коршунов В.М.','Коршунов Владислав Михайлович');adminState.updateAgentConfig(id,config);}
}
